"""Checks generated page copy against docs/VOICE.md. Exit code 1 if any banned pattern is found.

  python tools/voice_lint.py dist/quantum/index.html
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

BANNED_WORDS = ["landscape", "journey", "unlock", "revolutionis", "revolutioniz", "game-changer", "game changer", "cutting-edge",
                "state-of-the-art", "poised", "robust", "seamless", "leverage", "paradigm", "testament", "realm", "ever-evolving",
                "delve", "dive into", "tapestry", "navigate", "in today's", "worth noting", "at the end of the day",
                "drafted with ai", "ai-generated", "generated by ai", "ai assistance"]
PATTERNS = {
    "em dash": r"—|&mdash;|&#8212;",
    "en dash used as a dash": r" – |&ndash;",
    "not X but Y": r"\bnot (just|only|merely|simply)?\s*[\w' -]{1,40},? but\b",
    "it is not about": r"\b(it'?s|it is|this is) not about\b",
    "rhetorical question": r"[A-Z][^.!?<>]{15,}\?\s",
}


def visible_text(raw: str) -> str:
    raw = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", raw, flags=re.S)
    raw = re.sub(r"<svg.*?</svg>", " ", raw, flags=re.S)
    return html.unescape(re.sub(r"<[^>]+>", " ", raw))


def lint(raw: str) -> list[str]:
    text = visible_text(raw)
    low = text.lower()
    out = []
    for w in BANNED_WORDS:
        n = low.count(w)
        if n:
            out.append(f"banned word '{w}' x{n}")
    for name, pat in PATTERNS.items():
        for m in re.finditer(pat, text if name != "rhetorical question" else text, flags=re.I if name != "rhetorical question" else 0):
            out.append(f"{name}: ...{text[max(0, m.start() - 30):m.end() + 30].strip()}...")
    return out


if __name__ == "__main__":
    problems = lint(Path(sys.argv[1]).read_text(encoding="utf-8"))
    for p in problems:
        print(p)
    print(f"{len(problems)} problem(s)")
    sys.exit(1 if problems else 0)
